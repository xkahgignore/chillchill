(function() {
    'use strict';

    const CONFIG = {
        REPO_OWNER: 'xkahgignore',
        REPO_NAME: 'chillchill',
        BRANCH: 'main',
        SCRIPT_PATH: 'cryptolinkforearn/faucet.js',
        VERSION_PATH: 'cryptolinkforearn/version.json',
        CACHE_KEY: 'cryptolink_faucet_cache',
        VERSION_KEY: 'cryptolink_faucet_version',
        CACHE_TIME_KEY: 'cryptolink_faucet_cache_time',
        MAX_CACHE_AGE: 3600000
    };

    function getScriptUrl() {
        return 'https://raw.githubusercontent.com/' + CONFIG.REPO_OWNER + '/' + CONFIG.REPO_NAME + '/' + CONFIG.BRANCH + '/' + CONFIG.SCRIPT_PATH;
    }

    function getVersionUrl() {
        return 'https://raw.githubusercontent.com/' + CONFIG.REPO_OWNER + '/' + CONFIG.REPO_NAME + '/' + CONFIG.BRANCH + '/' + CONFIG.VERSION_PATH;
    }

    function log(message) {
        console.log('[Faucet]', message);
    }

    function logError(message) {
        console.error('[Faucet]', message);
    }

    function executeScript(content) {
        try {
            const script = document.createElement('script');
            script.textContent = content;
            document.documentElement.appendChild(script);
            log('Script executed successfully');
            return true;
        } catch(e) {
            logError('Failed to execute script: ' + e.message);
            return false;
        }
    }

    function loadFromGitHub(callback) {
        const url = getScriptUrl();
        log('Loading from: ' + url);

        GM_xmlhttpRequest({
            method: 'GET',
            url: url,
            cache: false,
            onload: function(response) {
                if (response.status === 200) {
                    log('Loaded successfully (' + response.responseText.length + ' bytes)');
                    callback(null, response.responseText);
                } else {
                    callback(new Error('HTTP ' + response.status));
                }
            },
            onerror: function(error) {
                callback(new Error('Network error'));
            },
            ontimeout: function() {
                callback(new Error('Timeout'));
            }
        });
    }

    function loadFromCache() {
        const content = GM_getValue(CONFIG.CACHE_KEY, null);
        const version = GM_getValue(CONFIG.VERSION_KEY, null);
        const time = GM_getValue(CONFIG.CACHE_TIME_KEY, 0);

        if (content && (Date.now() - time < CONFIG.MAX_CACHE_AGE)) {
            log('Using cached script (version: ' + version + ')');
            return { content, version, valid: true };
        }
        return { content: null, version: null, valid: false };
    }

    function saveCache(content, version) {
        GM_setValue(CONFIG.CACHE_KEY, content);
        GM_setValue(CONFIG.VERSION_KEY, version);
        GM_setValue(CONFIG.CACHE_TIME_KEY, Date.now());
        log('Cached script (version: ' + version + ')');
    }

    function checkVersion(callback) {
        GM_xmlhttpRequest({
            method: 'GET',
            url: getVersionUrl(),
            cache: false,
            onload: function(response) {
                try {
                    if (response.status === 200) {
                        const data = JSON.parse(response.responseText);
                        const currentVersion = GM_getValue(CONFIG.VERSION_KEY, '0.0.0');
                        log('Current: ' + currentVersion + ', Latest: ' + data.version);
                        callback(null, data.version > currentVersion, data.version);
                    } else {
                        callback(new Error('HTTP ' + response.status));
                    }
                } catch(e) {
                    callback(new Error('Invalid JSON'));
                }
            },
            onerror: function() {
                callback(new Error('Network error'));
            }
        });
    }

    function main() {
        log('Starting loader...');

        const cache = loadFromCache();
        if (cache.valid) {
            executeScript(cache.content);

            checkVersion(function(err, hasUpdate, newVersion) {
                if (err) {
                    logError('Version check failed: ' + err.message);
                    return;
                }

                if (hasUpdate) {
                    log('New version ' + newVersion + ' available, updating...');
                    loadFromGitHub(function(err, content) {
                        if (!err && content) {
                            saveCache(content, newVersion);
                            log('Updated to version ' + newVersion);
                            setTimeout(() => location.reload(), 1000);
                        } else {
                            logError('Update failed');
                        }
                    });
                }
            });
            return;
        }

        log('No valid cache found, loading from GitHub...');
        loadFromGitHub(function(err, content) {
            if (err) {
                logError('Failed to load from GitHub: ' + err.message);
                const expiredCache = GM_getValue(CONFIG.CACHE_KEY, null);
                if (expiredCache) {
                    log('Using expired cache as fallback');
                    executeScript(expiredCache);
                }
                return;
            }

            if (content) {
                GM_xmlhttpRequest({
                    method: 'GET',
                    url: getVersionUrl(),
                    onload: function(resp) {
                        try {
                            const data = JSON.parse(resp.responseText);
                            saveCache(content, data.version);
                        } catch(e) {
                            saveCache(content, '2026.8.19');
                        }
                        executeScript(content);
                    },
                    onerror: function() {
                        saveCache(content, '2026.8.19');
                        executeScript(content);
                    }
                });
            }
        });
    }

    main();

})();